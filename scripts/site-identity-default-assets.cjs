#!/usr/bin/env node
/**
 * Embeds the two DEFAULT files that have public alias routes (social.og, favicon.ico) into src/config/site-identity-default-assets.generated.ts, so the BE can serve the built-in default
 * (byte for byte) when nothing is published, without a redirect and without depending on a static folder in the deployed image.
 *   node scripts/site-identity-default-assets.cjs <FE-root> [--write | --check]
 * --check exits 1 when the checked-in module differs from the FE files (the default changed: review, then --write). The sha256 of each is also asserted against the registry fingerprint by a unit test.
 */
const fs = require('fs'); const path = require('path'); const crypto = require('crypto');
const [fe, mode = '--check'] = process.argv.slice(2);
if (!fe) { console.error('usage: site-identity-default-assets.cjs <FE-root> [--write|--check]'); process.exit(2); }
const FILES = { 'social.og': ['public/assets/social/waseetai-og-v3.jpg', 'image/jpeg'], 'favicon.ico': ['public/favicon.ico', 'image/x-icon'] };
let out = '// GENERATED by scripts/site-identity-default-assets.cjs from the FE public/ folder - do not edit. The built-in default files that have public alias routes (served unchanged when nothing is published).\n';
out += 'export interface DefaultAsset { mime: string; sha256: string; base64: string }\nexport const DEFAULT_ASSETS: Readonly<Record<string, DefaultAsset>> = {\n';
for (const [key, [rel, mime]] of Object.entries(FILES)) {
	const b = fs.readFileSync(path.join(fe, rel));
	out += `\t'${key}': { mime: '${mime}', sha256: '${crypto.createHash('sha256').update(b).digest('hex')}', base64: '${b.toString('base64')}' },\n`;
}
out += '};\n';
const target = path.join(__dirname, '..', 'src', 'config', 'site-identity-default-assets.generated.ts');
if (mode === '--write') { fs.writeFileSync(target, out); console.log('written', target); }
else if (fs.readFileSync(target, 'utf8') !== out) { console.error('DRIFT: default assets differ from the FE files'); process.exit(1); } else console.log('ok');
